#!/usr/bin/env node
/*
 * Embeds tools/page.html into src/pkjs/page.js so the PebbleKit JS bundle
 * can serve the debrief/config page as a data: URI.
 *
 * Run from the project root after editing page.html:
 *   node tools/build_page.js
 *
 * The page keeps three quoted placeholder tokens that index.js swaps for
 * real JSON at runtime:
 *   "__RUNLOG_RUNS__"  "__RUNLOG_CFG__"  "__RUNLOG_MILES__"  "__RUNLOG_INITIAL__"  "__RUNLOG_LOG__"
 */
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
var src = path.join(root, 'tools', 'page.html');
var dst = path.join(root, 'src', 'pkjs', 'page.js');

var html = fs.readFileSync(src, 'utf8');

// inject the shared TCX + FIT exporters (single source of truth with index.js)
var EXP_TOKEN = '/*__RUNLOG_EXPORTERS__*/';
if (html.split(EXP_TOKEN).length - 1 !== 1) {
  console.error('ERROR: expected exactly 1 ' + EXP_TOKEN + ' in page.html');
  process.exit(1);
}
var exporters = ['tcx', 'fit'].map(function (n) {
  return fs.readFileSync(path.join(root, 'src', 'pkjs', n + '.js'), 'utf8');
}).join('\n');
html = html.replace(EXP_TOKEN, exporters);

['"__RUNLOG_RUNS__"', '"__RUNLOG_CFG__"', '"__RUNLOG_MILES__"', '"__RUNLOG_INITIAL__"', '"__RUNLOG_LOG__"'].forEach(function (tok) {
  var n = html.split(tok).length - 1;
  if (n !== 1) {
    console.error('ERROR: expected exactly 1 occurrence of ' + tok + ', found ' + n);
    process.exit(1);
  }
});

var out =
  '/* GENERATED by tools/build_page.js from tools/page.html — do not edit. */\n' +
  'module.exports.TEMPLATE = ' + JSON.stringify(html) + ';\n';

fs.writeFileSync(dst, out);
console.log('wrote ' + dst + ' (' + out.length + ' bytes, page ' + html.length + ' bytes)');
