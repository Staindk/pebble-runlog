#!/usr/bin/env node
/*
 * Embeds tools/page.html into src/pkjs/page.js so the PebbleKit JS bundle
 * can serve the debrief/config page as a data: URI.
 *
 * Run from the project root after editing page.html or any injected shared
 * module (gpx.js, tcx.js, fit.js or smooth.js):
 *   node tools/build_page.js
 *
 * The page keeps six quoted placeholder tokens that index.js swaps for
 * real JSON at runtime:
 *   "__RUNLOG_RUNS__"  "__RUNLOG_CFG__"  "__RUNLOG_MILES__"  "__RUNLOG_INITIAL__"  "__RUNLOG_LOG__"  "__RUNLOG_DETAIL__"
 *
 * This file is also require()d by tools/test_export.js so the tests inject
 * exactly what the build injects. Keeping the list in one place matters: the
 * page and index.js MUST agree byte-for-byte on anything a download and an
 * upload both produce.
 */
var fs = require('fs');
var path = require('path');

var ROOT = path.join(__dirname, '..');
var EXP_TOKEN = '/*__RUNLOG_EXPORTERS__*/';

/* Modules in src/pkjs that the page runs verbatim. Each guards its
 * `module.exports`, so the same file works as a CommonJS require and as a plain
 * <script> body. GPX and the chart smoother used to be hand-copied into
 * page.html and had already drifted apart (different escaping, a missing
 * undefined check) before they were folded in here. */
var SHARED = ['gpx', 'tcx', 'fit', 'smooth'];

/* Every top-level function the shared modules define. If the page also declares
 * one, the later definition wins and silently reintroduces the drift, so the
 * build refuses rather than shipping two implementations. */
var SHARED_FNS = ['rlGpxBuild', 'rlTcxBuild', 'rlFitBuild', 'ksmooth'];

var PLACEHOLDERS = ['"__RUNLOG_RUNS__"', '"__RUNLOG_CFG__"', '"__RUNLOG_MILES__"',
                    '"__RUNLOG_INITIAL__"', '"__RUNLOG_LOG__"', '"__RUNLOG_DETAIL__"'];

function sharedSource(root) {
  return SHARED.map(function (n) {
    return fs.readFileSync(path.join(root || ROOT, 'src', 'pkjs', n + '.js'), 'utf8');
  }).join('\n');
}

function countOccurrences(hay, needle) {
  return hay.split(needle).length - 1;
}

/* Replace the exporter token in `src` with the shared modules. Throws on
 * anything that would produce a subtly wrong bundle. */
function inject(src, root) {
  if (countOccurrences(src, EXP_TOKEN) !== 1) {
    throw new Error('expected exactly 1 ' + EXP_TOKEN + ', found ' +
                    countOccurrences(src, EXP_TOKEN));
  }
  var out = src.replace(EXP_TOKEN, sharedSource(root));
  SHARED_FNS.forEach(function (fn) {
    var n = countOccurrences(out, 'function ' + fn);
    if (n !== 1) {
      throw new Error(fn + ' defined ' + n + ' times after injection (expected 1' +
                      ' — is there a stale copy in page.html?)');
    }
  });
  return out;
}

function render(root) {
  root = root || ROOT;
  var src = path.join(root, 'tools', 'page.html');
  var html = inject(fs.readFileSync(src, 'utf8'), root);

  PLACEHOLDERS.forEach(function (tok) {
    var n = countOccurrences(html, tok);
    if (n !== 1) {
      throw new Error('expected exactly 1 occurrence of ' + tok + ', found ' + n);
    }
  });

  return '/* GENERATED by tools/build_page.js from tools/page.html — do not edit. */\n' +
         'module.exports.TEMPLATE = ' + JSON.stringify(html) + ';\n';
}

function build() {
  var dst = path.join(ROOT, 'src', 'pkjs', 'page.js');
  var out = render(ROOT);
  fs.writeFileSync(dst, out);
  console.log('wrote ' + dst + ' (' + out.length + ' bytes)');
}

module.exports = {
  SHARED: SHARED,
  EXP_TOKEN: EXP_TOKEN,
  sharedSource: sharedSource,
  inject: inject,
  render: render
};

if (require.main === module) {
  try {
    build();
  } catch (e) {
    console.error('ERROR: ' + e.message);
    process.exit(1);
  }
}
